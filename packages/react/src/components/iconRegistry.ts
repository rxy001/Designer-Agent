export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

type RenderIconProps = LucideProps & {
  "data-slot"?: string;
};

export function renderIcon(name: IconName, props: RenderIconProps) {
  const IconComponent = ICONS[name];

  if (!IconComponent) {
    throw new Error(`Unknown Lucide icon: ${String(name)}`);
  }

  return createElement(IconComponent, props);
}

